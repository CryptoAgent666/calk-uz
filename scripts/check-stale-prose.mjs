const FILES = readdirSync('lib/data')
  .filter((f) => f.endsWith('.ts') && !f.includes('.bak'))
  .map((f) => `lib/data/${f}`)

let found = 0
for (const file of FILES) {
  // updates.ts — это changelog: он обязан цитировать старые значения
  if (file.endsWith('updates.ts')) continue
  const lines = readFileSync(file, 'utf8').split('\n')
  lines.forEach((line, i) => {
    // Числа сравниваем ЦЕЛИКОМ, а не подстрокой: «375 000» внутри «375 000 000»
    // — это не устаревшая БРВ, а первоначальный взнос. Прежний вариант с
    // lookbehind `(?<![\d ])` проваливал почти всю прозу: число почти всегда
    // стоит после пробела, и проверка молча его не видела.
    const tokens = new Set((line.match(/\d{1,3}(?: \d{3})+|\d+/g) || []).map((t) => t.replace(/ /g, '')))
    for (const s of STALE) {
      if (!tokens.has(s.was.replace(/ /g, ''))) continue
      // некоторые значения слишком обыденны сами по себе — нужен контекст факта
      if (s.ctx && !s.ctx.test(line)) continue
      // «с августа 2025 было 412 000» — законная история, а не недоехавшая правка
      if (HISTORICAL.test(line)) continue
      found++
      console.log(`${file}:${i + 1}  «${s.was}» — ${s.what}${s.now ? ` (сейчас ${s.now})` : ''}`)
      console.log(`   ${line.trim().slice(0, 160)}`)
    }
  })
}
if (found) {
  console.log(`\n✗ устаревших значений в прозе: ${found}`)
  console.log('\nЧто делать:')
  console.log('  • значение действительно протухло — обновите текст;')
  console.log('  • упоминание историческое и уместное (динамика ставок, changelog) —')
  console.log('    сузьте запись полем ctx или добавьте маркер в HISTORICAL,')
  console.log('    а не удаляйте запись из списка;')
  console.log('  • ставка сменилась — добавьте в STALE строку «было → стало»,')
  console.log('    и проверка сама покажет все места, куда правка не доехала.')
} else {
  console.log('\n✓ устаревших значений не найдено')
}
process.exit(found ? 1 : 0)
