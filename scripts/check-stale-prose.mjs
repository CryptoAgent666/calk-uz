#!/usr/bin/env node
/**
 * Ищет в прозе значения, которые КОГДА-ТО были верны, а теперь нет.
 *
 * Один факт живёт на сайте в пяти местах — константа, компонент, статья,
 * краткий ответ, пример, — и обновление регулярно доезжает не до всех. Этот
 * скрипт ловит именно такие хвосты: не «число не совпало с константой»
 * (слишком шумно из-за производных), а «в тексте стоит конкретное устаревшее
 * значение».
 *
 * Пополнять при каждой смене ставки: добавили новое значение — впишите старое.
 */
import { readFileSync, readdirSync } from 'node:fs'

// Историческое упоминание — законная причина увидеть старое число: динамика
// ставок, «до этого было», сравнение «было → стало». Такие строки пропускаем.
const HISTORICAL = /до этого|bundan oldin|ранее|было|edi|динамика|dinamikasi|до августа|до 1 сентября|bundan avval|o'sish/i

const STALE = [
  { was: '412 000',   now: '440 000',            what: 'БРВ до 1 сентября 2026 (УП-115)' },
  { was: '375 000',   now: '440 000',            what: 'БРВ до августа 2025' },
  { was: '330 000',   now: '440 000',            what: 'БРВ 2023' },
  { was: '1 271 000', now: '1 360 000',          what: 'МРОТ до 1 сентября 2026 (УП-115)', ctx: /МРОТ|МЗП|MIH|минимальн|minimal/i },
  { was: '1 155 000', now: '1 360 000',          what: 'МРОТ до августа 2025', ctx: /МРОТ|МЗП|MIH|минимальн/i },
  { was: '1 050 000', now: '1 360 000',          what: 'МРОТ 2024', ctx: /МРОТ|МЗП|MIH|минимальн/i },
  { was: '5 363 620', now: '5 739 200',          what: 'матпомощь 4,22 МРОТ до 1 сентября 2026' },
  { was: '101 680 000', now: '108 800 000',      what: 'льгота по ипотеке 80 МРОТ до 1 сентября 2026' },
  { was: '4 944 000 000', now: '5 280 000 000',  what: 'порог НДС 12 000 БРВ до 1 сентября 2026' },
  { was: '486',       now: '455',                what: 'гарантия по вкладам в БРВ до 1 сентября 2026', ctx: /вклад|omonat|гаранти|kafolat/i },
  { was: '65 000',    now: '160 000 / 192 000',  what: 'тариф ОСАГО до 2026 (ПКМ-458)', ctx: /ОСАГО|OSAGO/i },
  { was: '56 000',    now: '192 000',            what: 'тариф ОСАГО Ташкент до 2026', ctx: /ОСАГО|OSAGO/i },
  { was: '40 млн',    now: '80 млн',             what: 'лимит выплаты ОСАГО до 2026', ctx: /ОСАГО|OSAGO/i },
  { was: '1 738 640', now: '5 363 620',          what: 'матпомощь считалась в БРВ вместо МРОТ' },
  { was: '206 000 000', now: '101 680 000',      what: 'выдуманный вычет 500 БРВ' },
  { was: '878 000',   now: '983 000',            what: 'минимальная пенсия до июля 2026', ctx: /пенси|pensiya/i },
  { was: '820 000',   now: '983 000',            what: 'минимальная пенсия 2025', ctx: /пенси|pensiya/i },
  { was: '1 млрд',    now: '12 000 БРВ',         what: 'порог НДС до 1 июня 2026' },
  { was: '100 млрд',  now: null,                 what: 'выдуманный порог ежемесячной отчётности по НДС' },
]

const FILES = readdirSync('lib/data')
  .filter((f) => f.endsWith('.ts') && !f.includes('.bak'))
  .map((f) => `lib/data/${f}`)

let found = 0
for (const file of FILES) {
  // updates.ts — это changelog: он обязан цитировать старые значения
  if (file.endsWith('updates.ts')) continue
  const lines = readFileSync(file, 'utf8').split('\n')
  lines.forEach((line, i) => {
    // Числа сравниваем ЦЕЛИКОМ, а не подстрокой: «375 000» внутри «375 000 000»
    // — это не устаревшая БРВ, а первоначальный взнос. Прежний вариант с
    // lookbehind `(?<![\d ])` проваливал почти всю прозу: число почти всегда
    // стоит после пробела, и проверка молча его не видела.
    const tokens = new Set((line.match(/\d{1,3}(?: \d{3})+|\d+/g) || []).map((t) => t.replace(/ /g, '')))
    for (const s of STALE) {
      if (!tokens.has(s.was.replace(/ /g, ''))) continue
      // некоторые значения слишком обыденны сами по себе — нужен контекст факта
      if (s.ctx && !s.ctx.test(line)) continue
      // «с августа 2025 было 412 000» — законная история, а не недоехавшая правка
      if (HISTORICAL.test(line)) continue
      found++
      console.log(`${file}:${i + 1}  «${s.was}» — ${s.what}${s.now ? ` (сейчас ${s.now})` : ''}`)
      console.log(`   ${line.trim().slice(0, 160)}`)
    }
  })
}
if (found) {
  console.log(`\n✗ устаревших значений в прозе: ${found}`)
  console.log('\nЧто делать:')
  console.log('  • значение действительно протухло — обновите текст;')
  console.log('  • упоминание историческое и уместное (динамика ставок, changelog) —')
  console.log('    сузьте запись полем ctx или добавьте маркер в HISTORICAL,')
  console.log('    а не удаляйте запись из списка;')
  console.log('  • ставка сменилась — добавьте в STALE строку «было → стало»,')
  console.log('    и проверка сама покажет все места, куда правка не доехала.')
} else {
  console.log('\n✓ устаревших значений не найдено')
}
process.exit(found ? 1 : 0)
